drop policy if exists "public read active affiliate offers" on public.affiliate_offers;
create policy "public read active affiliate offers" on public.affiliate_offers for select using (active=true and starts_at<=now() and (ends_at is null or ends_at>=now()));
drop policy if exists "editor manage affiliate offers" on public.affiliate_offers;
create policy "editor manage affiliate offers" on public.affiliate_offers for all using (public.is_editor()) with check (public.is_editor());
drop policy if exists "public read active membership plans" on public.membership_plans;
create policy "public read active membership plans" on public.membership_plans for select using (active=true);
drop policy if exists "editor manage membership plans" on public.membership_plans;
create policy "editor manage membership plans" on public.membership_plans for all using (public.is_editor()) with check (public.is_editor());

create or replace function public.increment_affiliate_click(p_offer_id uuid)
returns void language plpgsql security definer set search_path=public as $$
begin
  update public.affiliate_offers set clicks=clicks+1, updated_at=now() where id=p_offer_id and active=true;
end;
$$;
revoke all on function public.increment_affiliate_click(uuid) from public;
grant execute on function public.increment_affiliate_click(uuid) to anon, authenticated, service_role;
