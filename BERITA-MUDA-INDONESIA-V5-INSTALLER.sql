create or replace function public.rebuild_trending() returns void language plpgsql security definer set search_path=public as $$
begin
  truncate public.trending_content;
  insert into public.trending_content(content_type, content_id, score, rank)
  select content_type, content_id, score, row_number() over(order by score desc)::int
  from (
    select 'article'::text content_type, a.id content_id,
      (a.views * 1.0 + a.likes * 4.0 + a.shares * 7.0 + case when a.featured then 3 else 0 end) /
      greatest(1, extract(epoch from (now() - coalesce(a.published_at,a.created_at)))/3600.0 + 2) as score
    from public.articles a where a.status='published'
    union all
    select 'video'::text, v.id,
      (v.views * 1.0 + v.likes * 4.0 + v.shares * 7.0) /
      greatest(1, extract(epoch from (now() - v.created_at))/3600.0 + 2) as score
    from public.videos v where v.status='published'
  ) ranked;
end;
$$;

