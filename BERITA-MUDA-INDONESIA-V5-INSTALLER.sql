create policy "editor manage videos" on public.videos for all using (public.is_editor()) with check (public.is_editor());

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select using (auth.uid()=id);

drop policy if exists "public read trending" on public.trending_content;
create policy "public read trending" on public.trending_content for select using (true);

drop policy if exists "public read active ads" on public.ad_campaigns;
