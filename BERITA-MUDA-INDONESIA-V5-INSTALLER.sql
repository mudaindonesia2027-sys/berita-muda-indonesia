create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'editor' check (role in ('admin','editor')),
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('pageview','view','like','share','video_play','ad_impression','ad_click')),
  content_type text check (content_type in ('article','video','site','ad')),
  content_id uuid,
  path text,
  referrer text,
  session_id text,
  created_at timestamptz not null default now()
);

create table if not exists public.trending_content (
  content_type text not null check (content_type in ('article','video')),
  content_id uuid not null,
  score numeric not null default 0,
  rank integer not null default 999,
  calculated_at timestamptz not null default now(),
  primary key(content_type, content_id)
);

create table if not exists public.ad_campaigns (
  id uuid primary key default gen_random_uuid(),
  advertiser_name text not null,
  title text not null,
  placement text not null check (placement in ('top','inline','sidebar','video')),
  image_url text,
  target_url text not null,
  alt_text text,
  starts_at timestamptz not null default now(),
  ends_at timestamptz,
  active boolean not null default true,
  impressions bigint not null default 0,
  clicks bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
